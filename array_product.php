<?php
// array_product() is similar to array_sum(), but it multiplies all the values together.
// It only returns integer or float value.

//Practice 1
$numbers = [2, 4, 5];

print_r(array_product($numbers));

//Practice 2

$numbers = [1.5, 2, 4];

print_r(array_product($numbers));

//Practice 3

$items = [5, 4, 3];

